# Google colabربط الداتا ب
from google.auth import default
from google.colab import auth
import gspread
import pandas as pd

# 1. تسجيل الدخول والصلاحيات
auth.authenticate_user()
creds, _ = default()
gc = gspread.authorize(creds)

# 2. تحميل البيانات
print("جاري تحميل الداتا...")
url = "https://raw.githubusercontent.com/owid/covid-19-data/master/public/data/owid-covid-data.csv"
df = pd.read_csv(url)

# 3. اختيار الأعمدة وحذف الصفوف الفارغة
df = df[[
    "date",
    "location",
    "total_cases",
    "new_cases",
    "total_deaths",
    "new_deaths",
]]
df = df.dropna(subset=["total_cases"])

# 4. فلترة البيانات Google Sheets

df = df[df["location"] == "Egypt"]

print(f"تم تحميل {len(df)} صف")

# 5. فتح شيت
spreadsheet_name = "Covid_Live"
try:
  sh = gc.open(spreadsheet_name)
except gspread.SpreadsheetNotFound:
  sh = gc.create(spreadsheet_name)

sheet = sh.sheet1

# 6. مسح  القديم ورفع البيانات الجديدة
sheet.clear()
data_to_upload = [df.columns.values.tolist()] + df.fillna("").values.tolist()
sheet.update(data_to_upload)

print("✅ تم تحديث الشيت بنجاح")
